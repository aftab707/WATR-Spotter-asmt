"""Pure Recommendation Engine for Weather-Aware Truck Routing.

Implements route ranking and comparative recommendation text generation.
Per Sections 1, 3, & 6 of PROJECT_SPEC.md:
- 5-tier ascending sort key:
    (no_travel_miles, severe_miles, high_miles, avg_risk, duration_minutes)
- Miles rounded to 0.1 and avg_risk to 0.01 to prevent floating-point noise.
- Strict hazard rule:
    * Any route with no_travel_miles > 0 is flagged is_recommended = False.
    * If all routes encounter No Travel, all are unrecommended and a warning is emitted.
- Human-readable recommendation_reason generated by comparing against the fastest route.
"""

from collections.abc import Sequence
from dataclasses import dataclass

from planner.logic.summary import RouteSummary


@dataclass
class RouteRecommendationInput:
    """Input structure representing a route candidate ready for evaluation."""

    id: str
    label: str
    distance_miles: float
    duration_minutes: float
    summary: RouteSummary


@dataclass
class RankedRoute:
    """Evaluated route candidate with recommendation rank, flag, and comparative reason."""

    id: str
    label: str
    rank: int
    is_recommended: bool
    distance_miles: float
    duration_minutes: float
    summary: RouteSummary
    recommendation_reason: str


@dataclass
class RecommendationResult:
    """Overall outcome of the recommendation engine."""

    recommended_route_id: str | None
    routes: list[RankedRoute]
    warnings: list[str]


def compute_route_sort_key(route: RouteRecommendationInput) -> tuple[float, float, float, float, float]:
    """Compute 5-tier ascending sort key.

    Priority order:
    1. no_travel_miles (ascending)
    2. severe_miles (ascending)
    3. high_miles (ascending)
    4. avg_risk (ascending)
    5. duration_minutes (ascending)

    Miles are rounded to 0.1 and avg_risk to 0.01 to eliminate float jitter.
    """
    s = route.summary
    return (
        round(s.no_travel_miles, 1),
        round(s.severe_miles, 1),
        round(s.high_miles, 1),
        round(s.avg_risk, 2),
        round(route.duration_minutes, 1),
    )


def generate_recommendation_reason(
    route: RouteRecommendationInput,
    is_recommended: bool,
    fastest_route: RouteRecommendationInput,
    recommended_route: RouteRecommendationInput | None,
) -> str:
    """Generate human-readable reason text comparing against the fastest route."""
    # 1. Unrecommended route encountering No Travel conditions
    if route.summary.no_travel_miles > 0:
        return (
            f"Not recommended: encounters {route.summary.no_travel_miles:.1f} miles of "
            f"No Travel weather hazards."
        )

    # 2. Recommended route
    if is_recommended:
        if route.id == fastest_route.id:
            if route.summary.severe_miles == 0 and route.summary.high_miles == 0:
                return "Fastest route with minimal weather risk."
            return "Fastest route with the lowest weather hazard exposure."

        # Recommended route is safer than the fastest route
        time_diff = round(route.duration_minutes - fastest_route.duration_minutes)
        severe_reduction = round(fastest_route.summary.severe_miles - route.summary.severe_miles, 1)
        high_reduction = round(fastest_route.summary.high_miles - route.summary.high_miles, 1)

        parts = [f"+{time_diff} min vs fastest"]
        if severe_reduction > 0:
            parts.append(f"{severe_reduction:.1f} fewer Severe miles")
        elif high_reduction > 0:
            parts.append(f"{high_reduction:.1f} fewer High miles")
        else:
            parts.append(
                f"lower average risk ({route.summary.avg_risk:.2f} vs {fastest_route.summary.avg_risk:.2f})"
            )

        return ", ".join(parts) + "."

    # 3. Non-recommended alternative route
    if route.id == fastest_route.id and recommended_route is not None:
        severe_added = round(route.summary.severe_miles - recommended_route.summary.severe_miles, 1)
        high_added = round(route.summary.high_miles - recommended_route.summary.high_miles, 1)
        if severe_added > 0:
            return f"Fastest route, but adds {severe_added:.1f} Severe miles vs recommended route."
        if high_added > 0:
            return f"Fastest route, but adds {high_added:.1f} High miles vs recommended route."
        return "Fastest route, but has higher weather hazard exposure."

    # Slower alternative with higher risk
    if recommended_route is not None:
        time_diff = round(route.duration_minutes - recommended_route.duration_minutes)
        time_str = f"+{time_diff} min vs recommended" if time_diff > 0 else "Slower"
        return f"{time_str}, with higher overall weather hazard."

    return "Alternative route option."


def rank_and_recommend_routes(
    routes: Sequence[RouteRecommendationInput],
) -> RecommendationResult:
    """Rank route candidates according to weather risk and duration, selecting the safest viable path.

    Evaluation process:
    1. Sort routes ascending by: (no_travel_miles, severe_miles, high_miles, avg_risk, duration_minutes).
    2. Find the fastest route among all candidates for comparative explanation.
    3. Identify candidate rank #1:
        - If rank #1 has no_travel_miles == 0, mark as is_recommended = True.
        - If rank #1 has no_travel_miles > 0, NO routes are viable; emit warning.
    4. Generate comparative reason strings for each route.
    """
    if not routes:
        return RecommendationResult(
            recommended_route_id=None,
            routes=[],
            warnings=["No routes provided for evaluation."],
        )

    # 1. Identify fastest route
    fastest_route = min(routes, key=lambda r: r.duration_minutes)

    # 2. Sort routes lexicographically
    sorted_candidates = sorted(routes, key=compute_route_sort_key)

    warnings: list[str] = []
    top_candidate = sorted_candidates[0]

    # Check for No Travel condition on top candidate
    if top_candidate.summary.no_travel_miles > 0:
        recommended_route_id = None
        recommended_route = None
        warnings.append("All routes encounter No Travel weather hazards. Travel is not recommended.")
    else:
        recommended_route_id = top_candidate.id
        recommended_route = top_candidate

    ranked_routes: list[RankedRoute] = []
    for rank_idx, candidate in enumerate(sorted_candidates):
        is_rec = (candidate.id == recommended_route_id) and (candidate.summary.no_travel_miles == 0)
        reason = generate_recommendation_reason(
            route=candidate,
            is_recommended=is_rec,
            fastest_route=fastest_route,
            recommended_route=recommended_route,
        )

        ranked_routes.append(
            RankedRoute(
                id=candidate.id,
                label=candidate.label,
                rank=rank_idx + 1,
                is_recommended=is_rec,
                distance_miles=candidate.distance_miles,
                duration_minutes=candidate.duration_minutes,
                summary=candidate.summary,
                recommendation_reason=reason,
            )
        )

    return RecommendationResult(
        recommended_route_id=recommended_route_id,
        routes=ranked_routes,
        warnings=warnings,
    )
